#!/usr/bin/env python3
"""Merge data/*.json into CATALOG.md (by category) and data/catalog.json (deduped)."""
import json, glob, os, re
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TYPE_ORDER = ["skill", "plugin", "mcp", "agent", "dashboard", "artifact", "workflow",
              "automation", "tool", "guide", "experiment", "announcement"]
TYPE_TITLES = {"skill": "Claude skills", "plugin": "Plugins", "mcp": "MCP servers / connectors",
               "agent": "Agents", "dashboard": "Dashboards", "artifact": "Artifacts & apps",
               "workflow": "Workflows", "automation": "Automations", "tool": "Tools adopted",
               "guide": "Guides & how-tos", "experiment": "Experiments", "announcement": "Announcements"}

def norm(s): return re.sub(r"[^a-z0-9]+", "-", (s or "").lower()).strip("-")

items = {}
for path in sorted(glob.glob(os.path.join(ROOT, "data", "*.json"))):
    if path.endswith("catalog.json"): continue
    for it in json.load(open(path)):
        key = norm(it.get("id") or it.get("name"))
        it.setdefault("sources", []).append(it.get("source", {}))
        if key in items:  # merge duplicates across sources
            old = items[key]
            old["sources"] += it["sources"]
            old["links"] = old.get("links", []) + [l for l in it.get("links", []) if l not in old.get("links", [])]
            old["tags"] = sorted(set(old.get("tags", [])) | set(it.get("tags", [])))
            old["updated"] = max(filter(None, [old.get("updated"), it.get("updated"), it.get("date")]), default=None)
        else:
            items[key] = it

allitems = sorted(items.values(), key=lambda x: x.get("updated") or x.get("date") or "", reverse=True)
json.dump(allitems, open(os.path.join(ROOT, "data", "catalog.json"), "w"), indent=1, ensure_ascii=False)

by_type = defaultdict(list)
for it in allitems:
    t = it.get("type", "tool")
    by_type[t if t in TYPE_ORDER else "tool"].append(it)

def row(it):
    links = " · ".join(f"[{l.get('label','link')}]({l['url']})" for l in it.get("links", [])[:3] if l.get("url"))
    src = it["sources"][0] if it["sources"] else {}
    where = f"[{src.get('channel') or src.get('kind','src')}]({src['permalink']})" if src.get("permalink") else (src.get("channel") or src.get("kind", ""))
    owners = ", ".join(it.get("owners", []))
    tags = " ".join(f"`{t}`" for t in it.get("tags", [])[:6])
    status = it.get("status", "")
    return f"| **{it['name']}** | {it.get('summary','').replace('|','/')} | {owners} | {it.get('date','')} | {status} | {tags} | {links} {where} |"

out = ["# AI Catalog — what Superside has built with AI", "",
       "_Generated by `scripts/build_index.py` from `data/*.json`. Do not edit by hand — edit the data files._", "",
       f"**{len(allitems)} items.** Search this file (or ask Claude) by problem keyword, e.g. `decks`, `resize`, `hours`, `brief`, `Figma`.", "",
       "## Contents"]
for t in TYPE_ORDER:
    if by_type[t]: out.append(f"- [{TYPE_TITLES[t]}](#{norm(TYPE_TITLES[t])}) ({len(by_type[t])})")
out += ["", "## Newest 15", ""]
for it in allitems[:15]:
    out.append(f"- {it.get('updated') or it.get('date','')} — **{it['name']}**: {it.get('summary','')}")
for t in TYPE_ORDER:
    if not by_type[t]: continue
    out += ["", f"## {TYPE_TITLES[t]}", "",
            "| Name | What it does | Who | Date | Status | Tags | Links |", "|---|---|---|---|---|---|---|"]
    out += [row(it) for it in by_type[t]]

# tag index
tagmap = defaultdict(list)
for it in allitems:
    for tg in it.get("tags", []): tagmap[tg.lower()].append(it["name"])
out += ["", "## Find by problem (tag index)", ""]
for tg in sorted(tagmap):
    out.append(f"- **{tg}**: " + ", ".join(sorted(set(tagmap[tg]))))
open(os.path.join(ROOT, "CATALOG.md"), "w").write("\n".join(out) + "\n")
print(f"{len(allitems)} items -> CATALOG.md, data/catalog.json")
